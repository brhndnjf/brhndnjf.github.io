'use strict';

/* Kerangka HTML untuk halaman catatan dan daftar catatan. */

const markdown = require('./markdown');
const esc = markdown.esc;

const SITE = 'https://brhndnjf.github.io';
const GENERATED = '<!-- generated by tools/build-notes.js — jangan sunting langsung -->';

const STATUS = {
  seedling: { label: 'Benih', icon: '🌱', cls: 'is-seed' },
  budding: { label: 'Tumbuh', icon: '🌿', cls: 'is-bud' },
  evergreen: { label: 'Abadi', icon: '🌲', cls: 'is-ever' }
};

function formatDate(iso) {
  return new Intl.DateTimeFormat('id-ID', {
    day: 'numeric', month: 'long', year: 'numeric'
  }).format(new Date(iso + 'T12:00:00'));
}

function statusBadge(note) {
  const s = STATUS[note.status];
  return '<span class="status ' + s.cls + '">' + s.icon + ' ' + s.label + '</span>';
}

const THEME_SCRIPT = [
  '  <script>',
  '    (function () {',
  '      try {',
  "        var t = localStorage.getItem('brh.theme');",
  "        if (t !== 'dark' && t !== 'light') {",
  '          var h = new Date().getHours();',
  "          t = (h >= 18 || h < 6) ? 'dark' : 'light';",
  '        }',
  "        if (t === 'dark') document.documentElement.setAttribute('data-theme', 'dark');",
  '      } catch (e) {',
  '        var hh = new Date().getHours();',
  "        if (hh >= 18 || hh < 6) document.documentElement.setAttribute('data-theme', 'dark');",
  '      }',
  '    })();',
  '  </script>'
].join('\n');

function pageHead(title, description, url, type) {
  return [
    '<!DOCTYPE html>',
    '<html lang="id">',
    '<head>',
    '  <meta charset="UTF-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
    '  <meta name="theme-color" content="#FAFAF9" media="(prefers-color-scheme: light)">',
    '  <meta name="theme-color" content="#1C1917" media="(prefers-color-scheme: dark)">',
    '',
    '  <title>' + esc(title) + '</title>',
    '  <meta name="description" content="' + esc(description) + '">',
    '',
    '  <meta property="og:type" content="' + type + '">',
    '  <meta property="og:title" content="' + esc(title) + '">',
    '  <meta property="og:description" content="' + esc(description) + '">',
    '  <meta property="og:url" content="' + esc(url) + '">',
    '  <meta name="twitter:card" content="summary">',
    '  <link rel="canonical" href="' + esc(url) + '">',
    '',
    "  <link rel=\"icon\" href=\"data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><rect width='100' height='100' rx='22' fill='%23E4572E'/><text x='50' y='68' font-size='54' font-family='system-ui' font-weight='600' fill='white' text-anchor='middle'>b</text></svg>\">",
    '',
    '  <link rel="preconnect" href="https://fonts.googleapis.com">',
    '  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    '  <link href="https://fonts.googleapis.com/css2?family=Libre+Baskerville:wght@400;700&family=Inter:wght@400;600&family=Source+Code+Pro:wght@400&display=swap" rel="stylesheet">',
    '',
    '  <link rel="stylesheet" href="/assets/css/tokens.css">',
    '  <link rel="stylesheet" href="/assets/css/base.css">',
    '  <link rel="stylesheet" href="/assets/css/hub.css">',
    '  <link rel="stylesheet" href="/assets/css/notes.css">',
    '',
    THEME_SCRIPT,
    '</head>'
  ].join('\n');
}

function topBar() {
  return [
    '    <header class="top">',
    '      <a class="top-mark" href="/"><b>brhndnjf</b> / taman digital</a>',
    '      <div class="theme" data-theme-hint>',
    '        <span class="theme-note">',
    '          <span data-theme-state>Tema otomatis</span>',
    '          <span data-theme-time></span>',
    '          <button class="theme-auto" type="button" data-theme-auto hidden>Ikuti jam</button>',
    '        </span>',
    '        <button class="theme-toggle" type="button" data-theme-toggle aria-label="Ganti tema terang atau gelap" aria-pressed="false">',
    '          <svg class="i-moon" viewBox="0 0 24 24" aria-hidden="true"><path d="M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8Z"/></svg>',
    '          <svg class="i-sun" viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="4"/><path d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4"/></svg>',
    '        </button>',
    '      </div>',
    '    </header>'
  ].join('\n');
}

function footBar() {
  return [
    '    <footer class="foot">',
    '      <span>© ' + new Date().getFullYear() + ' brhndnjf</span>',
    '      <span>',
    '        <a href="/catatan/">Catatan</a>',
    '        ·',
    '        <a href="https://github.com/brhndnjf/brhndnjf.github.io" rel="noopener">Kode sumber</a>',
    '        ·',
    '        <a href="#isi">Ke atas</a>',
    '      </span>',
    '    </footer>'
  ].join('\n');
}

function page(options) {
  return [
    pageHead(options.title, options.description, options.url, options.type || 'website'),
    '<body>',
    '  <a class="skip" href="#isi">Lewati ke konten</a>',
    '  <div class="wrap">',
    topBar(),
    '    <main id="isi">',
    options.body,
    '    </main>',
    footBar(),
    '  </div>',
    '  <script src="/assets/js/theme.js" defer></script>',
    options.scripts || '',
    '</body>',
    '</html>',
    ''
  ].join('\n');
}

module.exports = {
  SITE: SITE,
  GENERATED: GENERATED,
  STATUS: STATUS,
  formatDate: formatDate,
  statusBadge: statusBadge,
  page: page
};
